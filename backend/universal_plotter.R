# universal_plotter.R
# R Visualization Template for Standardized Comparison
library(jsonlite)
library(ggplot2)

# Load and Force Types
# The script expects analysis_output.json in the current working directory
if (!file.exists("analysis_output.json")) {
    stop("Error: analysis_output.json not found.")
}

df <- fromJSON("analysis_output.json")

# Basic validation
if (length(df) == 0) {
    stop("Error: No data in analysis_output.json")
}

# Force Types to prevent ggplot2 errors
df$category <- as.factor(df$category)
df$value <- as.numeric(df$value)

# Generate Plot
plot <- ggplot(df, aes(x = category, y = value, fill = category)) +
  geom_bar(stat = "identity", width = 0.6) +
  theme_minimal() +
  labs(
      title = "Comparative Analysis", 
      x = "Category", 
      y = "Average Value",
      subtitle = "Generated by Universal Agentic Analyst"
  ) +
  theme(legend.position = "none")

# Save Output
ggsave("plot_output.png", plot = plot, width = 8, height = 5, dpi = 300)
cat("✅ Plot saved to plot_output.png\n")
